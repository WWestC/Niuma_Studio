// typedefs.go — the JSDoc emitter: renders web/wire/gen/types.js from
// the contract — the ten wire payload types' FULL field mirrors
// (tag-for-tag, type-mapped). This is the "TS type emitter" the
// architecture roadmap kept promising: the field-complete JS mirror
// becomes a generated artifact, so a Go mirror field lands on the
// frontend's type surface by running wiregen, not by hand-copying
// @property lines. Consumption-shaped typedefs (subsets, projections)
// stay hand-written in wire.js; the full mirrors alias these.
package gen

import (
	"fmt"
	"strings"
)

// jsType maps a rendered Go type string onto its JSDoc counterpart.
// Pair-family names resolve to the generated typedef names (same
// identifiers as the Go wire types).
func jsType(goType string, pairWire map[string]bool) string {
	t := normWireType(goType)
	// Unwrap slices and pointers one level at a time.
	ptr := strings.HasPrefix(t, "*")
	t = strings.TrimPrefix(t, "*")
	slice := strings.HasPrefix(t, "[]")
	t = strings.TrimPrefix(t, "[]")
	var base string
	switch t {
	case "string":
		base = "string"
	case "bool":
		base = "boolean"
	case "int", "int64", "uint", "uint64", "float64":
		base = "number"
	case "any", "interface{}":
		base = "*"
	default:
		if pairWire[t] || strings.Contains(t, ".") {
			base = t // a wire payload type — the generated typedef's name
		} else if strings.HasPrefix(t, "map[string]string") {
			base = "Object.<string, string>"
		} else {
			base = "*" // unknown shape: keep the doc honest, not wrong
		}
	}
	if strings.HasPrefix(goType, "map[") {
		return "Object.<string, " + base + ">"
	}
	if slice {
		base = "Array.<" + base + ">"
	}
	if ptr {
		base = "?" + base
	}
	return base
}

// TypedefNames lists the payload types types.js carries (the wireconv
// pair family), in stable order.
var TypedefNames = func() []string {
	seen := map[string]bool{}
	var names []string
	for _, p := range Pairs {
		if !seen[p.Wire] {
			seen[p.Wire] = true
			names = append(names, p.Wire)
		}
	}
	return names
}()

// GenTypedefs renders gen/types.js from the contract.
func GenTypedefs(c *Contract) []byte {
	pairWire := map[string]bool{}
	for _, p := range Pairs {
		pairWire[p.Wire] = true
	}
	var b strings.Builder
	b.WriteString("// Code generated by tools/wiregen; DO NOT EDIT.\n")
	b.WriteString("// types.js — wire 载荷型的 JSDoc 全量镜像，由 frame-contract.json 生成\n")
	b.WriteString("//（`go run ./tools/wiregen`）。字段级真相在 Go wire 镜像的注释里；\n")
	b.WriteString("// wire.js 的消费面子集/带散文的 typedef 保留手写，全量镜像从这里别名。\n")
	b.WriteString("// contract.test.js 把本文件钉到契约上（双向）——改字段后重跑 wiregen 即同步。\n\n")
	for _, name := range TypedefNames {
		fields := c.Types[name]
		fmt.Fprintf(&b, "/**\n * @typedef {Object} %s — wire.%s 的全量镜像（生成物）。\n", name, name)
		for _, f := range fields {
			tag := strings.SplitN(f.Tag, ",", 2)[0]
			if tag == "" || tag == "-" {
				continue
			}
			optional := strings.Contains(f.Tag, ",omitempty")
			typ := jsType(f.Type, pairWire)
			if optional {
				fmt.Fprintf(&b, " * @property {%s} [%s]\n", typ, tag)
			} else {
				fmt.Fprintf(&b, " * @property {%s} %s\n", typ, tag)
			}
		}
		b.WriteString(" */\n\n")
	}
	b.WriteString("export {}; // ES module marker (JSDoc-only file)\n")
	return []byte(b.String())
}
